/** A methods-section summary of a model: equations, parameters, initial conditions and numerical method. */
import { symbolToLatex } from '../core/expr';
import type { OdeModel } from '../core/ode';
import { exprTex } from './tex';

const METHOD_TEXT = {
  rk45: (m: OdeModel) => `the adaptive Dormand--Prince Runge--Kutta 5(4) method with relative tolerance ${m.tol ?? 1e-8}`,
  ros23: (m: OdeModel) => `an adaptive linearly implicit Rosenbrock 2(3) method with relative tolerance ${m.tol ?? 1e-6}`,
  rk4: (m: OdeModel) => `the classical fourth-order Runge--Kutta method with a fixed step of ${m.dt}`,
  euler: (m: OdeModel) => `the explicit Euler method with a fixed step of ${m.dt}`,
};

const tex = exprTex;
/** Escape text for LaTeX running prose. */
const esc = (s: string) => s.replace(/([#$%&_{}])/g, '\\$1').replace(/\^/g, '\\^{}').replace(/~/g, '\\~{}');
/** siunitx-free unit: upright text with superscripts kept readable. */
const unitTex = (u?: string) => (u ? `\\,\\mathrm{${u.replace(/²/g, '^{2}').replace(/³/g, '^{3}').replace(/·/g, '\\,').replace(/°/g, '^{\\circ}').replace(/Ω/g, '\\Omega ').replace(/µ/g, '\\mu ').replace(/%/g, '\\%')}}` : '');

export function paperSummary(model: OdeModel, format: 'latex' | 'markdown'): string {
  const method = model.method ?? 'rk4';
  const solver = `The equations were integrated from $t = 0$ to $t = ${model.tEnd}$ using ${METHOD_TEXT[method](model)}.`;
  const events = (model.events ?? []).filter((e) => e.when.trim());
  const eqs = [
    ...model.states.map((s) => `\\frac{\\mathrm{d}${symbolToLatex(s.name)}}{\\mathrm{d}t} &= ${tex(s.deriv)}`),
    ...model.derived.map((d) => `${symbolToLatex(d.name)} &= ${tex(d.expr)}`),
  ];
  const inits = model.states.map((s) => `${symbolToLatex(s.name)}(0) = ${tex(s.init)}${unitTex(s.unit)}`).join(',\\quad ');

  if (format === 'latex') {
    return [
      `% ${esc(model.name)} — generated by Physics Tooling`,
      '\\begin{align}',
      eqs.map((e) => `  ${e}`).join(' \\\\\n'),
      '\\end{align}',
      `with initial conditions $${inits}$.`,
      ...events.map((e) => `Whenever $${tex(e.when)}$ becomes true, the state is reset according to $${e.then.split(/[;\n]/).map((a) => a.trim()).filter(Boolean).map((a) => { const [l, ...r] = a.split('='); return `${symbolToLatex(l.trim())} \\to ${tex(r.join('=').trim())}`; }).join(',\; ')}$.`),
      ...(model.stopWhen ? [`Integration stops when $${tex(model.stopWhen)}$.`] : []),
      '',
      '\\begin{table}[h]',
      '  \\centering',
      '  \\begin{tabular}{llr}',
      '    \\hline',
      '    Symbol & Description & Value \\\\',
      '    \\hline',
      ...model.params.map((p) => `    $${symbolToLatex(p.name)}$ & ${esc(p.label ?? '')} & $${p.value}${unitTex(p.unit)}$ \\\\`),
      '    \\hline',
      '  \\end{tabular}',
      `  \\caption{Parameters of the model.}`,
      '\\end{table}',
      '',
      solver,
      '',
    ].join('\n');
  }
  return [
    `### ${model.name}`,
    '',
    '$$',
    '\\begin{aligned}',
    eqs.join(' \\\\\n'),
    '\\end{aligned}',
    '$$',
    '',
    `Initial conditions: $${inits}$.`,
    ...events.map((e) => `\nEvent: when \`${e.when}\`, set \`${e.then}\`.`),
    ...(model.stopWhen ? [`\nIntegration stops when \`${model.stopWhen}\`.`] : []),
    '',
    '| Symbol | Description | Value |',
    '| --- | --- | --- |',
    ...model.params.map((p) => `| $${symbolToLatex(p.name)}$ | ${p.label ?? ''} | ${p.value}${p.unit ? ` ${p.unit}` : ''} |`),
    '',
    solver.replace(/--/g, '–'),
    '',
  ].join('\n');
}
