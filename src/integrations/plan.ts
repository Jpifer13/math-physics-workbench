import { APP_NAME } from '../core/brand';
import type { OdeModel, SolverMethod } from '../core/ode';
import { ExportError, parseResets } from './translate';

/** A model reduced to exactly what a code generator needs. */
export interface Plan {
  name: string;
  params: { name: string; value: number; unit?: string; label?: string }[];
  states: { name: string; init: string; deriv: string; unit?: string }[];
  derived: { name: string; expr: string }[];
  events: { when: string; resets: { state: string; expr: string }[] }[];
  stopWhen?: string;
  tEnd: number;
  method: SolverMethod;
  /** Relative tolerance to request from the target's adaptive solver. */
  rtol: number;
  /** Largest step, so the output is dense enough to plot. */
  maxStep: number;
  /** Every name the model defines, plus time. */
  names: string[];
}

export function planOf(model: OdeModel): Plan {
  if (!model.states.length) throw new ExportError('The model has no state variables');
  const states = model.states.map((s) => s.name);
  const method = model.method ?? 'rk4';
  const adaptive = method === 'rk45' || method === 'ros23';
  return {
    name: model.name || 'Untitled simulation',
    params: model.params.map(({ name, value, unit, label }) => ({ name, value, unit, label })),
    states: model.states.map(({ name, init, deriv, unit }) => ({ name, init, deriv, unit })),
    derived: model.derived.map(({ name, expr }) => ({ name, expr })),
    events: (model.events ?? []).filter((e) => e.when.trim()).map((e) => ({ when: e.when, resets: parseResets(e.then, states) })),
    stopWhen: model.stopWhen?.trim() || undefined,
    tEnd: model.tEnd,
    method,
    // Fixed-step methods have no counterpart elsewhere; ask the target for a tight adaptive solve instead.
    rtol: adaptive ? model.tol && model.tol > 0 ? model.tol : method === 'ros23' ? 1e-6 : 1e-8 : 1e-9,
    maxStep: model.tEnd / 400,
    names: ['t', ...model.params.map((p) => p.name), ...states, ...model.derived.map((d) => d.name)],
  };
}

export const headerLines = (plan: Plan, target: string, solver: string): string[] => [
  `Generated by ${APP_NAME} — ${plan.name}`,
  `Target: ${target}. Solver: ${solver}, relative tolerance ${plan.rtol}.`,
  ...(plan.method === 'rk4' || plan.method === 'euler'
    ? [`The model uses a fixed-step method in ${APP_NAME}; this script uses a tight adaptive solve instead.`]
    : []),
  'Writes result.csv (or the path given as the first argument): time, state variables, observables.',
];
