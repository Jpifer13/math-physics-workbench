import { translate, type Dialect } from './translate';

const model = (id: string) => MODELS.find((m) => m.id === id)!;

describe('expression translation is closed against injection', () => {
  const plain: Dialect = {
    number: String, constant: (n) => n, negate: (a) => `-${a}`, not: (a) => `!${a}`,
    binary: (op, a, b) => `(${a} ${op} ${b})`, call: (n, a) => `${n}(${a.join(',')})`, conditional: (c, a, b) => `(${c}?${a}:${b})`,
  };
  const known = (n: string) => (['x', 'k'].includes(n) ? n : undefined);
  it('rejects anything that is not a known name, operator or function', () => {
    for (const bad of ['__import__("os").system("rm -rf ~")', 'system("calc")', 'x; y', 'eval(x)', 'x.y', 'x[1]', '"text"', 'k = 3', 'f(x) = x', 'import("os")', 'secret + 1']) {
      expect(() => translate(bad, plain, known), bad).toThrow();
    }
  });
  it('re-emits from the syntax tree rather than copying text', () => {
    expect(translate('k*x ^ 2   # a comment', plain, known)).toBe('(k * (x ^ 2))');
  });
  it('refuses to export a model with an expression it cannot translate', () => {
    const hostile: OdeModel = { ...model('pendulum'), derived: [{ name: 'E', expr: 'eval("1")' }] };
    for (const t of TARGETS) expect(() => t.generate(hostile), t.id).toThrow(/cannot be exported|does not define/);
  });
});

describe('generators', () => {
  it('produce a script for every template in every target', () => {
    for (const t of TARGETS) for (const m of MODELS) {
      const code = t.generate(m);
      expect(code.length, `${t.id}/${m.id}`).toBeGreaterThan(200);
      expect(code, `${t.id}/${m.id}`).toContain('Generated by Physics Tooling');
    }
  });
  it('renames reserved words and target-specific hazards', () => {
    const tricky: OdeModel = {
      ...model('pendulum'),
      params: [{ name: 'lambda', value: 2, min: 0, max: 5 }, { name: 'end', value: 1, min: 0, max: 5 }, { name: 'E_0', value: 1, min: 0, max: 5 }],
      states: [{ name: 'x', init: 'E_0', deriv: '-lambda * x * end' }],
      derived: [], events: [],
    };
    expect(generatePython(tricky)).toContain('lambda_ = 2.0');
    expect(generatePython(tricky)).toMatch(/return \[\(\(\(-lambda_\) \* x\) \* end\)\]/);
    expect(generateMatlab(tricky)).toContain('end_ = 1;');
    // Wolfram symbols cannot contain underscores, and E is Euler's number there.
    expect(generateMathematica(tricky)).toContain('mEu0 = 1.;');
  });
  it('map language-specific argument orders and constants', () => {
    const m: OdeModel = { ...model('pendulum'), states: [{ name: 'x', init: '1', deriv: 'atan2(x, 2) + log(x, 10) + 1e-7 * e' }], params: [], derived: [], events: [] };
    expect(generateMathematica(m)).toContain("ArcTan[2., mx[t]]");
    expect(generateMathematica(m)).toContain('Log[10., mx[t]]');
    expect(generateMathematica(m)).toContain('1.*^-7');
    expect(generateMatlab(m)).toContain('(log(y(1)) / log(10))');
  });
});

/** Run a generated script and compare every column with this app's own solver. */
function crossCheck(command: string, args: (script: string) => string[], file: string, code: string, m: OdeModel, tolerance: number) {
  const dir = mkdtempSync(join(tmpdir(), 'physics-tooling-'));
  try {
    writeFileSync(join(dir, file), code);
    execFileSync(command, args(file), { cwd: dir, timeout: 120000, stdio: 'pipe' });
    const cols = parseTable(readFileSync(join(dir, 'result.csv'), 'utf8'));
    const ours = simulate({ ...m, method: 'rk45', tol: 1e-10 });
    expect(ours.error).toBeUndefined();
    const t = cols[0].values;
    expect(t.at(-1)!).toBeCloseTo(ours.t.at(-1)!, 4);
    for (const c of cols.slice(1)) {
      const mine = ours.series[c.name];
      expect(mine, c.name).toBeDefined();
      // Scale by the size of the quantity, so a conserved value (zero spread) is compared sensibly.
      const span = Math.max(Math.max(...mine) - Math.min(...mine), Math.max(...mine.map(Math.abs)), 1e-12);
      let worst = 0;
      // Skip the instants of discontinuity, where the two outputs sample different sides of a jump.
      const jumps = ours.eventTimes ?? [];
      t.forEach((ti, i) => {
        if (jumps.some((te) => Math.abs(te - ti) < 1e-3)) return;
        const v = interpolate(ours.t, mine, ti);
        if (Number.isFinite(v)) worst = Math.max(worst, Math.abs(v - c.values[i]) / span);
      });
      expect(worst, `${m.id}: ${c.name}`).toBeLessThan(tolerance);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const has = (command: string, args: string[]) => {
  try { execFileSync(command, args, { stdio: 'pipe', timeout: 30000 }); return true; } catch { return false; }
};
const python = has('python3', ['-c', 'import scipy, numpy']);
const octave = has('octave', ['--version']);

describe.skipIf(!python)('Python export reproduces this app\'s results (needs SciPy)', () => {
  // Chaotic systems amplify rounding differences, so the Lorenz template is checked over a short horizon only.
  const cases: [string, Partial<OdeModel>, number][] = [
    // The tolerance is set by linear interpolation between this app's recorded samples, not by either solver.
    ['projectile', {}, 1e-3], ['bounce', {}, 1e-3], ['pendulum', {}, 1e-3], ['oscillator', { tEnd: 20 }, 1e-3],
    ['orbit', { tEnd: 15 }, 1e-3], ['lorenz', { tEnd: 5 }, 5e-3], ['cyclotron', {}, 1e-3], ['vdp', { tEnd: 20 }, 5e-3],
    ['rlc', {}, 1e-3], ['coupled', { tEnd: 20 }, 1e-3],
  ];
  for (const [id, patch, tol] of cases) {
    it(id, () => {
      const m = { ...model(id), ...patch, method: 'rk45' as const, tol: 1e-9 };
      crossCheck('python3', (f) => [f], 'physics_model.py', generatePython(m), m, tol);
    }, 180000);
  }
});

describe.skipIf(!octave)('MATLAB/Octave export reproduces this app\'s results (needs GNU Octave)', () => {
  const cases: [string, Partial<OdeModel>, number][] = [
    ['projectile', {}, 2e-3], ['bounce', {}, 2e-3], ['pendulum', {}, 2e-3], ['oscillator', { tEnd: 20 }, 2e-3],
    ['orbit', { tEnd: 15 }, 2e-3], ['lorenz', { tEnd: 4 }, 1e-2], ['cyclotron', {}, 2e-3], ['vdp', { tEnd: 20, method: 'ros23', tol: 1e-7 }, 1e-2],
    ['rlc', {}, 2e-3], ['coupled', { tEnd: 20 }, 2e-3],
  ];
  for (const [id, patch, tol] of cases) {
    it(id, () => {
      const m = { ...model(id), method: 'rk45' as const, tol: 1e-8, ...patch };
      crossCheck('octave', (f) => ['--no-gui', '--quiet', f], 'physics_model.m', generateMatlab(m), m, tol);
    }, 180000);
  }
});
